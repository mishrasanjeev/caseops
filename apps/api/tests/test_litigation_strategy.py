def test_strategy_persists_with_audit_event(
    client: TestClient, mock_strategy_provider,
) -> None:
    token, _, matter_id = _setup_matter(client, forum_level="high_court")
    response = client.post(
        f"/api/matters/{matter_id}/recommendations",
        headers=auth_headers(token),
        json={"type": "litigation_strategy"},
    )
    assert response.status_code == 200
    rec_id = response.json()["id"]

    # Verify the persisted row + audit row.
    factory = get_session_factory()
    with factory() as session:
        rec = session.scalar(
            select(Recommendation).where(Recommendation.id == rec_id)
        )
        assert rec is not None
        assert rec.type == "litigation_strategy"
        assert rec.review_required is True
        assert rec.strategy_payload_json is not None
        # Round-trips through the Pydantic model.
        round_trip = LitigationStrategyPayload.model_validate(
            json.loads(rec.strategy_payload_json),
        )
        assert round_trip.recommended_route.label

        audit_events = list(
            session.scalars(
                select(AuditEvent).where(
                    AuditEvent.target_id == rec_id,
                    AuditEvent.action == "recommendation.generated",
                )
            )
        )
        assert audit_events, "Strategy generation must write an audit row."
        meta = json.loads(audit_events[0].metadata_json or "{}")
        assert meta.get("type") == "litigation_strategy"
        assert meta.get("forum_steps", 0) >= 1


