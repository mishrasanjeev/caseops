def test_assert_no_forbidden_phrases_blocks_outcome_promises() -> None:
    """Every entry in FORBIDDEN_OUTCOME_PHRASES must be rejected — case-
    insensitive, anywhere in the string. This is the structural test
    the PRD §2 hard rule depends on."""
    for phrase in FORBIDDEN_OUTCOME_PHRASES:
        with pytest.raises(ValueError, match=phrase):
            assert_no_forbidden_phrases(
                f"This route is a {phrase} — file immediately."
            )
        # Case-insensitive — the production scan lowercases.
        with pytest.raises(ValueError):
            assert_no_forbidden_phrases(phrase.upper())


